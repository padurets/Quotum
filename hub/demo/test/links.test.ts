import test from 'node:test';
import assert from 'node:assert/strict';
import type {AddressInfo} from 'node:net';
import {buildApp} from '../../server/api.js';
import {Store} from '../../server/store/store.js';
import {Directory} from '../../server/store/directory.js';
import {Ingest} from '../../server/ingest.js';
import {Duty} from '../../server/duty.js';
import {Cadence} from '../../server/cadence.js';
import {Pairing} from '../../server/pairing.js';
import {Setup} from '../../server/setup.js';
import {ResetFeed} from '../../server/resets.js';
import {composeMoneyWorkPrepared,moneyWorkRate} from '../../server/domain/moneyWork.js';
import {drain} from '../../server/domain/prepare.js';
import type {ClientLink,LinkInput,Attribution} from '../../server/domain/links.js';
import type {Snapshot} from '../../server/projection.js';
import {SETS,LINK_SCENES} from '../catalogue.js';
import {setUp} from '../setup.js';
import {seedLinks} from '../links.js';

test('linked-client catalogue codes hold through production reports, projections and history',async()=>{
  const now=Date.now(),hour=3_600_000,store=new Store(':memory:',now-2*hour),directory=new Directory(store.db);
  const app=await buildApp({store,directory,ingest:new Ingest(store,directory,new Duty(),new Cadence()),pairing:new Pairing(directory),setup:new Setup(true,'BCDF-GHJK'),resets:new ResetFeed(undefined,()=>{}),local:null});
  try{
    await app.listen({host:'127.0.0.1',port:0});
    const set=SETS.find(set=>set.id==='links')!,base='http://127.0.0.1:'+(app.server.address() as AddressInfo).port;
    const stand=await setUp(base,set,now,'BCDF-GHJK',()=>now,true);await seedLinks(store,directory,stand);
    const owner=stand.people.get('ana')!,seen=new Set<string>();
    const {links,sources}=await owner.get<{links:ClientLink[];sources:{name:string}[]}>('/api/links');
    assert.ok(sources.some(source=>source.name==='DeepSeek account 1')&&sources.some(source=>source.name==='DeepSeek account 2'));
    const {suggestions}=await owner.get<{suggestions:LinkInput[]}>('/api/links/suggestions');
    assert.equal(suggestions.length,1);seen.add('suggestion-one');
    assert.deepEqual([suggestions[0].from,suggestions[0].to],[now-hour,now+hour]);seen.add('shown-dates');
    assert.ok(links.some(link=>link.to===now-hour)&&links.some(link=>link.from===now+hour));seen.add('past-and-future-rules');
    const {sessions}=await owner.get<{sessions:(Attribution&{clientId:string;accountSourceId:string|null;host?:string})[]}>('/api/links/attribution');
    assert.ok(sessions.some(session=>session.route?.class==='subscription')&&sessions.some(session=>session.route?.class==='api'));seen.add('subscription-api');
    assert.ok(sessions.some(session=>session.route?.class==='unknown'&&session.source===null));seen.add('unknown-route');
    assert.ok(sessions.some(session=>session.route?.provider==='openrouter'&&session.source===null));seen.add('unbound-api');
    assert.ok(sessions.some(session=>session.disagreement==='account'&&session.source!==session.accountSourceId));seen.add('manual-disagreement');
    assert.ok(sessions.some(session=>session.by==='link'&&!session.active&&session.source===null&&session.accountSourceId));seen.add('inactive-mask');
    assert.ok(sessions.some(session=>session.otherGateway&&session.host==='gateway.example'));seen.add('private-gateway');
    assert.equal(suggestions.some(hint=>hint.route?.provider==='zai'),false);seen.add('suggestion-zero');
    assert.equal(suggestions.some(hint=>hint.route?.provider==='deepseek'),false);seen.add('suggestion-multiple');
    const snapshot=await owner.get<Snapshot>('/api/overview?board='+owner.personalBoard),names=snapshot.view.names;
    const source=(name:string)=>snapshot.sources.find(source=>names[source.id]===name)!;
    assert.equal(source('Claude complete observations').usageWork?.[0].quality,'confirmed');seen.add('quota-growth-confirmed');
    assert.equal(source('Claude incomplete observations').usageWork?.[0].quality,'partial');seen.add('quota-growth-partial');
    const shared=await owner.get<Snapshot>('/api/overview?board='+stand.boards.get('team'));
    const publicText=JSON.stringify(shared);assert.ok(!publicText.includes('gateway.example')&&!publicText.includes('accountSourceId')&&!publicText.includes('linkId'));
    assert.ok(shared.sources.some(source=>source.usageWork?.length));seen.add('shared-safe-status');
    const wallet=source('OpenRouter linked work').id,cell=60_000,from=Math.floor((now-2*hour)/cell)*cell,to=Math.ceil((now+1)/cell)*cell;
    const chunks=store.cells(owner.personalBoard,cell,from,to,{now,scope:'budget',sourceWork:true,meters:{unit:'USD',ids:[[wallet,'balance']]}});
    const work=drain(composeMoneyWorkPrepared(chunks,cell,from,to))[0],estimate=moneyWorkRate(work,'14000000');
    assert.equal(work.eligibleActiveMs,hour);assert.equal(estimate.rate,'1400000');seen.add('active-hour-rate');
    assert.equal(estimate.remainingMs,String(10*hour));seen.add('remaining-active-hours');
    assert.equal(source('DeepSeek account 1').meters?.find(meter=>meter.id==='balance:USD')?.amount,'25000000');
    assert.deepEqual(store.moneyWorkSources(owner.personalBoard,{unit:'USD',ids:[[source('DeepSeek account 1').id,'balance:USD']]}),[]);seen.add('balance-only-unsupported');
    for(const scene of LINK_SCENES)for(const code of scene.expect)assert.ok(seen.has(code),scene.id+': '+code);
  }finally{await app.close();store.close();}
});
